"""Our reproduction of the paper's Tables 5-7, in the paper's layout.

    python tables.py   -> results/TABLES_5_7.csv and results/TABLES_5_7.md

Settings from DECISIONS.md (kuwano.py defaults), 174A in visible-text order. The last
column shows the paper's value wherever ours differs, so the tables can be checked
against the PDF line by line.
"""
from __future__ import annotations

import csv
import os
import sys

import kuwano as kw
from validate import FIELDS, paper_rows

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "results")
TITLES = {"AA22-277A": "Table 5", "AA22-138B": "Table 6", "AA22-174A": "Table 7"}
HEAD = {"prediction": "Prediction", "tp": "TP", "fp": "FP", "tn": "TN", "fn": "FN"}


def main():
    data, seqs, paper = kw.load(), kw.load_sequences(), paper_rows()
    rows = []
    md = ["# Reproduced Tables 5-7", "",
          "Generated by `tables.py` from `kuwano.py` with the settings in DECISIONS.md. "
          "'Paper' shows the published value only where ours differs.", ""]
    total = same = 0
    for adv, v in seqs.items():
        seq = v["variants"]["visible_text"] if "variants" in v else v["sequence"]
        pos = dict(zip(v["sequence"], v["listed_tactic"]))
        got = kw.evaluate(seq, [pos[t] for t in seq], data)
        md += [f"## {TITLES[adv]}: Confusion matrix ({adv})", "",
               "| Input | Prediction | TP | FP | TN | FN | Paper |", "|---|---|---|---|---|---|---|"]
        for r in got:
            want = paper[adv][r["input"]]
            diff = [f"{HEAD[f]} {want[f]}" for f in FIELDS if r[f] != want[f]]
            total += 1
            same += not diff
            md.append(f"| {r['input']} | {r['prediction']} | {r['tp']} | {r['fp']} | {r['tn']} | {r['fn']} | "
                      f"{', '.join(diff) if diff else 'same'} |")
            rows.append({"report": adv, "input": r["input"], **{f: r[f] for f in FIELDS},
                         "matches_paper": int(not diff)})
        md.append("")
    md.append(f"Rows identical to the paper on all five numbers: {same} of {total}.")
    with open(os.path.join(OUT, "TABLES_5_7.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(OUT, "TABLES_5_7.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md) + "\n")
    print(f"{same}/{total} rows identical to the paper; written to results/TABLES_5_7.csv and .md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
