"""Paired held-out reanalysis and a declared parameter sensitivity study.

Run from any directory: python code/revision_analysis.py
No network access is used. All data are synthetic and generated by the submitted
simulator. The vectorized evaluator is checked against its episode-level outputs.
The perturbation grid is specified below; every setting is retained in the CSVs.
"""
from __future__ import annotations
from dataclasses import dataclass, asdict, replace
from pathlib import Path
import json, platform, sys, hashlib
import numpy as np
import pandas as pd
import scipy
from scipy.stats import wilcoxon
import run_experiments as sim

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'revision_results'
OUT.mkdir(exist_ok=True)
METRICS = ['utility','redirection_precision','engagement_rate',
           'benign_false_redirect_rate','unsafe_action_rate','normalized_cost']

@dataclass(frozen=True)
class Setting:
    name: str = 'default'
    family: str = 'default'
    weights: tuple = (.34,.27,.22,.17)
    threshold_shift: float = 0.
    evidence: int = 6
    ood_limit: float = 2.2
    confidence_min: float = .55
    uncertainty_scale: float = 1.
    residual_bound: int = 1
    capture_scale: float = 1.
    outcome_cost_scale: float = 1.
    outcome_benign_scale: float = 1.

def grid():
    base = Setting()
    specs = [base]
    for name,weights in [('equal',(.25,.25,.25,.25)),
                         ('confidence',(.5,.2,.2,.1)),('stage',(.2,.2,.2,.4))]:
        specs.append(replace(base,name='weights_'+name,family='risk weights',weights=weights))
    axes = [
        ('threshold_shift','action thresholds',[-.05,.05]),
        ('evidence','evidence gate',[3,12]),
        ('ood_limit','OOD gate',[1.65,2.75]),
        ('confidence_min','confidence gate',[.45,.65]),
        ('uncertainty_scale','uncertainty margin',[.5,1.5]),
        ('residual_bound','residual bound',[0,2]),
        ('capture_scale','outcome capture',[.8,1.2]),
        ('outcome_cost_scale','outcome resource cost',[.5,1.5]),
        ('outcome_benign_scale','outcome benign harm',[.5,1.5]),
    ]
    for key,family,values in axes:
        for value in values:
            specs.append(replace(base,name=f'{key}_{value}',family=family,**{key:value}))
    for shift in [-.05,0.,.05]:
        for margin in [.5,1.,1.5]:
            # Axis-aligned points are already represented above; add only the
            # four genuinely joint perturbations (26 unique settings in all).
            if shift == 0 or margin == 1:
                continue
            specs.append(replace(base,name=f'joint_{shift}_{margin}',family='joint threshold and margin',
                                 threshold_shift=shift,uncertainty_scale=margin))
    return specs

def inputs():
    episodes,meta=[] ,[]
    for dataset in ['primary','ood']:
        for seed in range(sim.N_SEEDS):
            for scenario in sim.SCENARIOS:
                for attacker in (sim.ATTACKERS if dataset == 'primary' else sim.OOD_ATTACKER):
                    episodes.append(sim.generate_episode(seed,scenario,attacker,ood=dataset=='ood'))
                    meta.append({'dataset':dataset,'seed':seed,'scenario':scenario,'attacker':attacker})
    events=[ev for episode in episodes for ev in episode]
    keys=['confidence','severity','criticality','stage','completeness','capacity',
          'malicious','ideal','capture_draw']
    x={k:np.array([e[k] for e in events]) for k in keys}
    features=np.array([[e['observed_features'] for e in episode] for episode in episodes])
    conf=x['confidence'].reshape(len(episodes),sim.EVENTS_PER_EPISODE)
    qualified=conf >= sim.PROFILE_UPDATE_CONFIDENCE
    n=np.cumsum(qualified,axis=1)-qualified
    totals=np.cumsum(features*qualified[:,:,None],axis=1)-features*qualified[:,:,None]
    profiles=np.where(n[:,:,None]>0,totals/np.maximum(n[:,:,None],1),.5)
    x['profile']=profiles.reshape(-1,5)
    x['qualified']=n.ravel()
    centers=np.stack(list(sim.ATTACKERS.values()))
    scale=np.array([.23,.23,.23,.20,.20])
    x['distance']=np.sqrt((((x['profile'][:,None,:]-centers[None,:,:])/scale)**2).sum(axis=2)).min(axis=1)
    # The policy inputs contain no malicious/benign truth or ideal action.
    return x,pd.DataFrame(meta),episodes

def decisions(x,setting):
    risk=sum(w*x[k] for w,k in zip(setting.weights,['confidence','severity','criticality','stage']))
    # Correct the stage component, whose raw range is 0--3.
    risk -= setting.weights[3]*x['stage']*(1-1/sim.MAX_ATTACK_STAGE)
    adjusted=risk*(.88+.12*x['completeness'])
    base=np.digitize(adjusted,np.array(sim.CONSENSUS_THRESHOLDS)+setting.threshold_shift)
    latent=.42*x['severity']+.23*x['criticality']+.18*x['profile'][:,3]+.17*x['profile'][:,4]
    ideal=np.where(latent<.47,1,np.where(latent<.72,2,3))
    actions=np.arange(4)[None,:]
    capture=np.array([.05,.51,.77,.91])[None,:]*np.exp(-.42*np.abs(actions-ideal[:,None]))*(.86+.14*x['completeness'][:,None])
    cost=sim.ACTION_COST[None,:]/x['capacity'][:,None]
    mv=.34+capture*.54+(1-capture)*.08*actions-.13*np.maximum(ideal[:,None]-actions,0)-.075*np.maximum(actions-ideal[:,None],0)-cost
    bv=.82-cost-np.array([0,.045,.39,.64])[None,:]
    pm=np.clip((risk-.22)/.48,.02,.98)[:,None]
    value=pm*mv+(1-pm)*bv
    eligible=np.abs(actions-base[:,None])<=setting.residual_bound
    candidate=np.argmax(np.where(eligible,value,-np.inf),axis=1)
    rows=np.arange(len(base))
    uncertainty=setting.uncertainty_scale*(.11/np.sqrt(np.maximum(x['qualified'],1))+.025*x['distance'])
    gain=value[rows,candidate]-value[rows,base]
    reason=np.full(len(base),'personalized',dtype='<U24')
    reason[gain-1.645*uncertainty<0]='noninferiority'
    reason[(candidate>base)&(x['confidence']<setting.confidence_min)]='confidence'
    reason[x['distance']>setting.ood_limit]='ood_context'
    reason[x['qualified']<setting.evidence]='insufficient_evidence'
    admitted=reason=='personalized'
    return base,np.where(admitted,candidate,base),reason

def evaluate(x,actions,setting,meta,reasons=None):
    a=actions
    cp=np.clip(np.array([.05,.51,.77,.91])[a]*np.exp(-.42*np.abs(a-x['ideal']))*(.86+.14*x['completeness'])*setting.capture_scale,0,.98)
    captured=x['capture_draw']<cp
    malicious=x['malicious'].astype(bool)
    cost=sim.ACTION_COST[a]/x['capacity']
    mu=.34+np.where(captured,.54,.08*a)-.13*np.maximum(0,x['ideal']-a)-.075*np.maximum(0,a-x['ideal'])-cost*setting.outcome_cost_scale
    bu=.82-cost*setting.outcome_cost_scale-np.array([0,.045,.39,.64])[a]*setting.outcome_benign_scale
    utility=np.clip(np.where(malicious,mu,bu),0,1)
    unsafe=np.where(malicious,(a==3)&(x['confidence']<.42),a>=2)
    shape=(len(meta),sim.EVENTS_PER_EPISODE)
    sums=lambda vals:np.asarray(vals).reshape(shape).sum(axis=1)
    means=lambda vals:np.asarray(vals).reshape(shape).mean(axis=1)
    frame=meta.copy()
    frame['utility']=means(utility)
    frame['redirection_precision']=sums((a>=2)&captured&malicious)/np.maximum(sums(a>=2),1)
    frame['engagement_rate']=sums(malicious&(a>=1))/np.maximum(sums(malicious),1)
    frame['benign_false_redirect_rate']=sums((~malicious)&(a>=2))/np.maximum(sums(~malicious),1)
    frame['unsafe_action_rate']=means(unsafe)
    frame['normalized_cost']=means(cost)
    frame['fallback_rate']=1. if reasons is None else means(reasons!='personalized')
    frame['action_disagreement_rate']=np.nan
    return frame

def seed_average(frame):
    return frame.groupby(['dataset','seed','policy'],as_index=False)[METRICS+['fallback_rate','action_disagreement_rate']].mean()

def ci(values,rng):
    return sim.bootstrap_ci(np.asarray(values,dtype=float),rng)

def paired(seed_frame,label,include_p=True):
    rows=[]
    for dataset in ['primary','ood']:
        sub=seed_frame[seed_frame.dataset==dataset]
        family=[]
        for metric in METRICS:
            pivot=sub.pivot(index='seed',columns='policy',values=metric).sort_index()
            d=pivot['CADO'].to_numpy()-pivot['Consensus'].to_numpy()
            rng=sim.derive_rng('revision-bootstrap',label,dataset,metric)
            lo,hi=ci(d,rng)
            lr,hr=ci(pivot['CADO'],rng)
            lc,hc=ci(pivot['Consensus'],rng)
            # Exact zero handling follows the submitted analysis.
            if np.allclose(d,0):
                stat,pvalue,dz=0.,1.,0.
            else:
                stat,pvalue=wilcoxon(d,alternative='two-sided',zero_method='wilcox',method='auto')
                dz=d.mean()/d.std(ddof=1) if d.std(ddof=1)>0 else float('nan')
            family.append({'setting':label,'dataset':dataset,'metric':metric,
                           'cado_mean':pivot['CADO'].mean(),'cado_ci_low':lr,'cado_ci_high':hr,
                           'consensus_mean':pivot['Consensus'].mean(),'consensus_ci_low':lc,'consensus_ci_high':hc,
                           'difference':d.mean(),'ci_low':lo,'ci_high':hi,
                           'wilcoxon_statistic':stat,'p_raw':pvalue,'effect_size_dz':dz,'n_paired_seeds':len(d),
                           'nonzero_pairs':int(np.count_nonzero(np.abs(d)>1e-14))})
        adj=sim.holm_adjust([r['p_raw'] for r in family])
        for r,p in zip(family,adj):
            r['p_holm_six_endpoints']=p
            rows.append(r)
    return rows

def main():
    settings=grid()
    (OUT/'sensitivity_settings.json').write_text(json.dumps([asdict(s) for s in settings],indent=2),encoding='utf-8')
    x,meta,episodes=inputs()
    print(f'Generated {len(meta)} episodes / {len(x["confidence"])} shared events; {len(settings)} settings.',flush=True)
    all_seeds=[]
    default_episodes=[]
    for setting in settings:
        base,cado,reasons=decisions(x,setting)
        c=evaluate(x,cado,setting,meta,reasons).assign(policy='CADO')
        c['action_disagreement_rate']=(base!=cado).reshape(len(meta),sim.EVENTS_PER_EPISODE).mean(axis=1)
        b=evaluate(x,base,setting,meta).assign(policy='Consensus')
        b['action_disagreement_rate']=0.
        frame=pd.concat([b,c],ignore_index=True)
        seeds=seed_average(frame).assign(setting=setting.name,family=setting.family)
        all_seeds.append(seeds)
        if setting.name=='default':
            default_episodes=frame
            frame.to_csv(OUT/'default_episode_reanalysis.csv',index=False)
            # Check every common scientific metric against submitted CSVs.
            errors=[]
            for dataset,filename in [('primary','primary_episode_metrics.csv'),('ood','ood_episode_metrics.csv')]:
                old=pd.read_csv(ROOT/'submitted_results'/filename)
                old=old[old.policy.isin(['Consensus','CADO'])]
                keys=['seed','scenario','attacker','policy']
                joined=frame[frame.dataset==dataset].merge(old,on=keys,suffixes=('_new','_submitted'),validate='one_to_one')
                for metric in METRICS:
                    err=float(np.max(np.abs(joined[metric+'_new']-joined[metric+'_submitted'])))
                    errors.append({'dataset':dataset,'metric':metric,'max_abs_error':err,'episodes':len(joined)})
                    assert err<1e-12,(dataset,metric,err)
            # Independently compare the scalar policy on a deterministic subset
            # spanning both datasets and all scenario types, with prior-only state.
            scalar_checked=0
            for ep_i in range(0,len(episodes),13):
                state=sim.PolicyState()
                for t,event in enumerate(episodes[ep_i]):
                    actual,reason=sim.choose_action('CADO',event,state)
                    assert actual == cado[ep_i*sim.EVENTS_PER_EPISODE+t]
                    state.update(event)
                    scalar_checked+=1
            # Latent outcomes cannot influence the decision function.
            flipped={**x,'malicious':~x['malicious'].astype(bool),'ideal':np.zeros_like(x['ideal']),'capture_draw':np.ones_like(x['capture_draw'])}
            assert np.array_equal(cado,decisions(flipped,setting)[1])
            (OUT/'reproduction_validation.json').write_text(json.dumps({'episode_comparisons':errors,'scalar_decisions_checked':scalar_checked,'latent_label_invariance':True},indent=2),encoding='utf-8')
            print('Default reproduced all submitted CADO/Consensus scientific metrics within 1e-12.',flush=True)
        print(setting.name, 'done',flush=True)
    seeds=pd.concat(all_seeds,ignore_index=True)
    seeds.to_csv(OUT/'sensitivity_seed_metrics.csv',index=False)
    comparisons=[]
    for label,group in seeds.groupby('setting',sort=False):
        comparisons.extend(paired(group,label))
    comp=pd.DataFrame(comparisons)
    comp.to_csv(OUT/'sensitivity_paired_comparisons.csv',index=False)
    default=seeds[seeds.setting=='default']
    comp[comp.setting=='default'].to_csv(OUT/'primary_heldout_consensus_paired.csv',index=False)
    # The held-out family matches the original main analysis: 3 baselines x 6 metrics.
    old_ood=pd.read_csv(ROOT/'submitted_results/ood_episode_metrics.csv')
    os=old_ood.groupby(['seed','policy'],as_index=False)[METRICS].mean()
    held=[]
    for metric in METRICS:
        pivot=os.pivot(index='seed',columns='policy',values=metric).sort_index()
        for baseline in ['Static','Adaptive','Consensus']:
            d=(pivot['CADO']-pivot[baseline]).to_numpy()
            if np.allclose(d,0): stat,p,dz=0.,1.,0.
            else:
                stat,p=wilcoxon(d,alternative='two-sided',zero_method='wilcox',method='auto')
                dz=d.mean()/d.std(ddof=1) if d.std(ddof=1)>0 else float('nan')
            lo,hi=ci(d,sim.derive_rng('heldout-paired-18',metric,baseline))
            held.append({'metric':metric,'comparison':f'CADO - {baseline}','mean_difference':d.mean(),
                         'ci_low':lo,'ci_high':hi,'wilcoxon_statistic':stat,'p_raw':p,'effect_size_dz':dz,
                         'n_paired_seeds':len(d),'nonzero_pairs':int(np.count_nonzero(np.abs(d)>1e-14))})
    for row,p in zip(held,sim.holm_adjust([r['p_raw'] for r in held])): row['p_holm']=p
    pd.DataFrame(held).to_csv(OUT/'heldout_paired_statistical_comparisons.csv',index=False)
    summary=[]
    for (policy,),group in os.groupby(['policy']):
        for metric in METRICS:
            lo,hi=ci(group[metric],sim.derive_rng('heldout-summary',policy,metric))
            summary.append({'policy':policy,'metric':metric,'mean':group[metric].mean(),'ci_low':lo,'ci_high':hi,'n':30})
    pd.DataFrame(summary).to_csv(OUT/'heldout_summary_statistics.csv',index=False)
    (OUT/'revision_environment.json').write_text(json.dumps({'date':'2026-10-07','python':sys.version,
       'platform':platform.platform(),'numpy':np.__version__,'pandas':pd.__version__,'scipy':scipy.__version__,
       'master_seed':sim.MASTER_SEED,'bootstrap_resamples':10000,'settings':len(settings),
       'independent_unit':'seed; equally weighted scenario/attacker episode means',
       'sensitivity_status':'post-review exploratory; all declared settings retained; no model selection',
       'original_code_sha256':hashlib.sha256((ROOT/'code/run_experiments.py').read_bytes()).hexdigest()},indent=2),encoding='utf-8')
    print(pd.DataFrame(held).query("comparison == 'CADO - Consensus'").to_string(index=False),flush=True)
    print('All revision analyses completed.',flush=True)

if __name__=='__main__':
    main()
