clear; clc;
fprintf('=== CoADAM Figure: MITRE ATT&CK Threat Profile Heatmap ===\n');

project_root = '/Users/ujw/Desktop/CoADAM';
fig_dir      = fullfile(project_root, 'figures');
if ~exist(fig_dir, 'dir'), mkdir(fig_dir); end

%% ---- Load verified threat profiles ----
tp = load(fullfile(project_root, 'data', 'processed', 'threat_profiles.mat'));

categories = {'Reconnaissance', 'InitialAccess', 'Execution', ...
              'LateralMovement', 'Impact', 'Benign'};
tactic_ids = {'TA0043', 'TA0001', 'TA0002', 'TA0008', 'TA0040', '---'};
datasets   = {'CIC-IIoT-2025', 'WUSTL-IIoT-2021', 'Edge-IIoTset'};
ds_keys    = {'cic', 'wustl', 'edge'};

n_cat = numel(categories);
n_ds  = numel(datasets);

%% ---- Extract values from struct ----
values = zeros(n_cat, n_ds);
for d = 1:n_ds
    for c = 1:n_cat
        values(c, d) = tp.threat_profiles.(ds_keys{d}).(categories{c}) * 100;
    end
end

fprintf('\nExtracted threat profile values (%%%):\n');
fprintf('%-20s %12s %12s %12s\n', 'Category', datasets{1}, datasets{2}, datasets{3});
fprintf('%s\n', repmat('-', 1, 60));
for c = 1:n_cat
    fprintf('%-20s %11.2f%% %11.2f%% %11.2f%%\n', ...
        categories{c}, values(c,1), values(c,2), values(c,3));
end

%% ---- Figure ----
fig = figure('Position', [50 50 1100 750], 'Color', 'w');

%% ---- Main heatmap axes (more left margin, less right) ----
ax_main = axes('Position', [0.22 0.14 0.55 0.68]);

%% ---- Draw heatmap cells ----
cell_w = 1.0;
cell_h = 1.0;

% Color maps per dataset column
c_maps = {[0.20 0.45 0.75], [0.85 0.35 0.20], [0.25 0.62 0.30]};

for c = 1:n_cat
    for d = 1:n_ds
        val     = values(c, d);
        max_val = max(values(c, :));

        % Normalize intensity within row
        if max_val > 0
            intensity = val / max_val;
        else
            intensity = 0;
        end

        % Cell color: white to dataset color
        base_col = c_maps{d};
        cell_col = 1 - intensity * (1 - base_col);

        % Draw cell
        x_pos = (d-1) * cell_w;
        y_pos = (n_cat - c) * cell_h;

        rectangle('Parent', ax_main, ...
            'Position',  [x_pos, y_pos, cell_w, cell_h], ...
            'FaceColor', cell_col, ...
            'EdgeColor', [0.82 0.82 0.82], ...
            'LineWidth', 1.2);

        % Value text
        if intensity > 0.55
            txt_col = [1 1 1];
        else
            txt_col = [0.15 0.15 0.15];
        end

        text(ax_main, x_pos + cell_w/2, y_pos + cell_h/2, ...
            sprintf('%.2f%%', val), ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment',   'middle', ...
            'FontName',   'Times New Roman', ...
            'FontSize',   12, ...
            'FontWeight', 'bold', ...
            'Color',      txt_col);
    end
end

%% ---- Axes formatting ----
xlim(ax_main, [0 n_ds]);
ylim(ax_main, [0 n_cat]);
axis(ax_main, 'off');

%% ---- Column headers (dataset names) — spaced above the grid ----
for d = 1:n_ds
    text(ax_main, (d-1) + cell_w/2, n_cat + 0.45, datasets{d}, ...
        'HorizontalAlignment', 'center', ...
        'FontName',   'Times New Roman', ...
        'FontSize',   12, ...
        'FontWeight', 'bold', ...
        'Color',      c_maps{d} * 0.75);
end

%% ---- Row labels (category + tactic ID) ----
for c = 1:n_cat
    y_pos = (n_cat - c) * cell_h + cell_h/2;

    % Category name
    text(ax_main, -0.12, y_pos + 0.15, categories{c}, ...
        'HorizontalAlignment', 'right', ...
        'FontName',   'Times New Roman', ...
        'FontSize',   11, ...
        'FontWeight', 'bold', ...
        'Color',      [0.15 0.15 0.15]);

    % Tactic ID
    text(ax_main, -0.12, y_pos - 0.18, tactic_ids{c}, ...
        'HorizontalAlignment', 'right', ...
        'FontName',   'Times New Roman', ...
        'FontSize',   9.5, ...
        'FontWeight', 'bold', ...
        'Color',      [0.50 0.50 0.50]);
end

%% ---- Legend (dataset color boxes) ----
legend_x = 0.82;
legend_y_start = 0.72;
legend_spacing = 0.10;

for d = 1:n_ds
    ly = legend_y_start - (d-1) * legend_spacing;

    annotation('rectangle', ...
        [legend_x, ly, 0.025, 0.04], ...
        'FaceColor', c_maps{d}, ...
        'EdgeColor', c_maps{d} * 0.75, ...
        'LineWidth', 1.5);
    annotation('textbox', ...
        [legend_x + 0.035, ly - 0.005, 0.15, 0.05], ...
        'String',    datasets{d}, ...
        'FontName',  'Times New Roman', ...
        'FontSize',  10, ...
        'FontWeight','bold', ...
        'Color',     c_maps{d} * 0.75, ...
        'EdgeColor', 'none', ...
        'FitBoxToText', 'on');
end

%% ---- Intensity note ----
annotation('textbox', ...
    [0.80, 0.38, 0.18, 0.08], ...
    'String',    {'Shading: relative', 'intensity per row'}, ...
    'FontName',  'Times New Roman', ...
    'FontSize',  9, ...
    'FontWeight','bold', ...
    'Color',     [0.45 0.45 0.45], ...
    'EdgeColor', [0.80 0.80 0.80], ...
    'BackgroundColor', [0.97 0.97 0.97], ...
    'LineWidth', 1.0);

%% ---- Title ----
annotation('textbox', ...
    [0.02, 0.91, 0.96, 0.07], ...
    'String',    'MITRE ATT&CK Threat Profile Distribution Across IIoT Datasets', ...
    'FontName',  'Times New Roman', ...
    'FontSize',  15, ...
    'FontWeight','bold', ...
    'HorizontalAlignment', 'center', ...
    'Color',     'k', ...
    'EdgeColor', 'none');

%% ---- Subtitle ----
annotation('textbox', ...
    [0.02, 0.86, 0.96, 0.05], ...
    'String',    'Values show percentage of training samples per category. Shading normalized per row.', ...
    'FontName',  'Times New Roman', ...
    'FontSize',  10, ...
    'FontWeight','bold', ...
    'HorizontalAlignment', 'center', ...
    'Color',     [0.45 0.45 0.45], ...
    'EdgeColor', 'none');

%% ---- Bottom note ----
annotation('textbox', ...
    [0.02, 0.02, 0.96, 0.05], ...
    'String',    'MITRE ATT&CK Tactics: TA0043 Reconnaissance | TA0001 InitialAccess | TA0002 Execution | TA0008 LateralMovement | TA0040 Impact', ...
    'FontName',  'Times New Roman', ...
    'FontSize',  9, ...
    'FontWeight','bold', ...
    'HorizontalAlignment', 'center', ...
    'Color',     [0.40 0.40 0.40], ...
    'EdgeColor', 'none');

%% ---- Save ----
exportgraphics(fig, fullfile(fig_dir, 'fig_mitre_heatmap.pdf'), ...
    'ContentType', 'vector');
exportgraphics(fig, fullfile(fig_dir, 'fig_mitre_heatmap.png'), ...
    'Resolution', 300);

fprintf('\nFigure saved: fig_mitre_heatmap.pdf and fig_mitre_heatmap.png\n');
fprintf('=== Done ===\n');
